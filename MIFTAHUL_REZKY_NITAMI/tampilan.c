void setcolor(int text, int background)
{
    SetConsoleTextAttribute(handle, background * 24 + text);
}    

void bingkai(int x, int y, int panjang, int lebar, int text, int background)
{
    for (int i = 0; i <= panjang; i++)
    {
        for (int j = 0; j <= lebar; j++)
        {
            if (i == 0 || i == panjang || j == 0 || j == lebar)
            {
                gotoxy(x + i, y + j);
                setcolor(text, background);
                printf("%c", 219);
            }
            else
            {
                gotoxy(x + i, y + j);
                setcolor(background, background);
                printf(" ");
            }
        }
    }
}

